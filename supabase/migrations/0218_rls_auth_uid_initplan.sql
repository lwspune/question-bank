-- 0218: access rules read the signed-in user once per query, not once per row
-- (TECH_DEBT_SPEC.md 3.2, 2026-11-05).
--
-- WHY. 63 of the 139 rules in `public` called `auth.uid()` bare (Supabase performance
-- advisor `auth_rls_initplan`; counted in pg_policies). Postgres inlines a bare
-- `auth.uid()` into the filter and evaluates it, a JSON parse of the request's login
-- claims, for EVERY row it checks, and an index on `user_id` cannot be used against it.
-- Written as `(select auth.uid())` it becomes an init plan: evaluated once, then
-- compared as a constant. Measured before, as the student with the most mock answers
-- (3,590): `select question_id from attempt_answers order by question_id` read all
-- 69,104 rows and parsed the claims on each of 1,598 mock_attempts rows; 69 ms on a
-- quiet database, 604 ms mean over 331 calls in pg_stat_statements under load.
--
-- WHAT. Each statement below is the rule's current text from pg_policies with every
-- bare `auth.uid()` wrapped, and nothing else changed: same commands, same roles,
-- same logic. Generated by a query over pg_policies on 2026-11-05 (rules already
-- using `( SELECT auth.uid() AS uid)` were left as they were). ALTER POLICY keeps
-- each rule's command, roles and permissive flag.
--
-- Not changed: the `private.current_user_*()` helpers in some rules. The advisor
-- does not flag them, and they are SECURITY DEFINER lookups whose own cost is
-- separate work.

alter policy answer_grade_disputes_insert_own on public.answer_grade_disputes
  with check (((user_id = ( SELECT auth.uid() AS uid)) AND (resolved_at IS NULL) AND (resolution IS NULL) AND (EXISTS ( SELECT 1
   FROM (answer_submissions s
     JOIN answer_grades g ON ((g.submission_id = s.id)))
  WHERE ((s.id = g.submission_id) AND (s.user_id = ( SELECT auth.uid() AS uid)) AND (s.status = 'graded'::text) AND (g."position" = answer_grade_disputes."position"))))));


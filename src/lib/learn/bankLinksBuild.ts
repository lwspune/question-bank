/**
 * Which bank chapter each Learn course chapter teaches (2026-11-27). Concept Ladder titles its
 * chapters with PYQ Vault's own names, so the title is the bank chapter's name within the course's
 * exam and subject; the few that differ are ALIASES. `npm run learn:links` runs this over the
 * bundle and the live taxonomy and writes bankLinks.generated.ts, which the Learn pages (practice
 * links, "From your mistakes") and V (Teach me) read. Pure: the script does the reading.
 * Spec: tests/learn-bank-links-build.test.ts.
 */
import type { LearnSubject } from "./subjects";

/** A bank chapter as the database names it. */
export type BankChapterRow = { exam: string; subject: string; chapter: string };

/** A Learn course chapter's bank chapter: the exam, subject and chapter names in the database. */
export type LearnBankChapter = BankChapterRow;

/** The bank subjects a Learn subject's chapters can sit in. "Maths" for JEE and MHT-CET; Algebra and Geometry are SSC 10's two Maths papers. */
export const BANK_SUBJECTS: Record<LearnSubject, readonly string[]> = {
  maths: ["Mathematics", "Maths", "Algebra", "Geometry"],
  physics: ["Physics"],
  chemistry: ["Chemistry"],
  biology: ["Biology"],
};

/** `<course>/<course chapter slug>` → the bank chapter's name, where it differs from the Learn title. */
export const ALIASES: Readonly<Record<string, string>> = {
  "mh-hsc-12-maths/line-and-plane": "Line and Planes",
  // 2026-11-27 import. The bank writes a hyphen where Concept Ladder's title has a dash.
  "mh-sb-11-maths/trigonometric-functions": "Trigonometry - I",
  "mh-sb-11-maths/compound-and-multiple-angles": "Trigonometry - II",
  "mht-cet-maths/compound-and-multiple-angles": "Trigonometry - II",
  "jee-mains-chemistry/organic-chemistry": "Organic Chemistry - Some Basic Principles and Techniques",
  "mh-sb-11-maths/permutations-and-combinations": "Permutations and Combination",
  "cbse-12-chemistry/d-and-f-block-elements": "The d-and f-Block Elements",
  "mht-cet-chemistry/p-block-16-17-18": "Elements of Group 16, 17 and 18",
  "mht-cet-chemistry/halogen-derivatives": "Halogen Derivatives of Alkanes",
};

type CourseIn = { slug: string; exam: string; subject: string; chapters: { slug: string; title: string }[] };

export function buildLearnBankChapters(
  courses: CourseIn[],
  bank: BankChapterRow[],
  examNameOf: (slug: string) => string | undefined,
): { links: Record<string, LearnBankChapter>; errors: string[] } {
  const links: Record<string, LearnBankChapter> = {};
  const errors: string[] = [];
  for (const course of courses) {
    const exam = examNameOf(course.exam);
    if (!exam) {
      errors.push(`${course.slug}: no exam ${course.exam} in the registry`);
      continue;
    }
    const subjects = BANK_SUBJECTS[course.subject as LearnSubject] ?? [];
    const taken = new Map<string, string>();
    for (const ch of course.chapters) {
      const key = `${course.slug}/${ch.slug}`;
      const name = ALIASES[key] ?? ch.title;
      const found = bank.filter((b) => b.exam === exam && subjects.includes(b.subject) && b.chapter === name);
      if (found.length !== 1) {
        errors.push(`${key}: ${found.length === 0 ? "no" : found.length} bank chapter "${name}" in ${exam} ${subjects.join("/")}`);
        continue;
      }
      const at = `${found[0].subject}|${found[0].chapter}`;
      const other = taken.get(at);
      if (other) {
        errors.push(`${key}: bank chapter "${name}" is already taught by ${other}`);
        continue;
      }
      taken.set(at, key);
      links[key] = { exam, subject: found[0].subject, chapter: found[0].chapter };
    }
  }
  return { links, errors };
}

export function renderBankLinksFile(links: Record<string, LearnBankChapter>, commit: string): string {
  const rows = Object.keys(links)
    .sort()
    .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(links[k]).replace(/":/g, '": ').replace(/,"/g, ', "')},`);
  return [
    "// Generated by `npm run learn:links` from Concept Ladder " + commit + " and the live taxonomy. Do not edit:",
    "// fix a name in ALIASES (src/lib/learn/bankLinksBuild.ts) and run it again.",
    'import type { LearnBankChapter } from "./bankLinksBuild";',
    "",
    "/** `<course>/<course chapter slug>` → the bank chapter it teaches. */",
    "export const LEARN_BANK_CHAPTERS: Readonly<Record<string, LearnBankChapter>> = {",
    ...rows,
    "};",
    "",
  ].join("\n");
}

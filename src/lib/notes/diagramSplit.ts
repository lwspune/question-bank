/**
 * Splits the notes diagram registry into what a live page needs.
 *
 * diagramRegistry.tsx imports every diagram and maps each slug to one. Ebooks
 * and scripts draw from it directly. A live notes page must not: importing a
 * browser-run ("use client") diagram from a server component puts it in the
 * script every notes page loads, and the page cannot respond to a tap until
 * that script arrives (2026-11-22: 150 diagrams, 172 KB compressed, done at
 * 4.6-4.9 s on a slow phone connection).
 *
 * So `npm run notes:diagrams` writes two files from the registry:
 * - serverDiagrams.generated.tsx: the picture-only diagrams, imported
 *   directly. They render on the server and send no browser code.
 * - ClientDiagram.generated.tsx: one `next/dynamic` loader per browser-run
 *   diagram, so a page downloads only the ones it shows.
 * Drift check: tests/notes-diagram-split.test.ts.
 */

export interface DiagramEntry {
  slug: string;
  component: string;
  /** File name under visualizations/, without .tsx. */
  file: string;
}

const IMPORT_RE = /^import (\w+) from "\.\/visualizations\/(\w+)";$/gm;
const CASE_RE = /^ {4}case "([a-z0-9-]+)":\n {6}return <(\w+) \/>;$/gm;

/** Read the registry's imports and cases. Throws on anything not wired both ways. */
export function parseDiagramRegistry(source: string): DiagramEntry[] {
  const src = source.replace(/\r\n/g, "\n");
  const fileOf = new Map<string, string>();
  for (const m of src.matchAll(IMPORT_RE)) fileOf.set(m[1], m[2]);

  const entries: DiagramEntry[] = [];
  const seen = new Set<string>();
  const used = new Set<string>();
  for (const m of src.matchAll(CASE_RE)) {
    const [, slug, component] = m;
    if (seen.has(slug)) throw new Error(`diagram slug "${slug}" is wired twice`);
    const file = fileOf.get(component);
    if (!file) throw new Error(`case "${slug}" returns <${component} /> but ${component} is not imported`);
    seen.add(slug);
    used.add(component);
    entries.push({ slug, component, file });
  }
  const unused = [...fileOf.keys()].filter((c) => !used.has(c));
  if (unused.length) throw new Error(`imported but no case uses it: ${unused.join(", ")}`);
  return entries;
}

/** True when a module opens with the "use client" directive. */
export function isClientSource(source: string): boolean {
  return /^["']use client["']/.test(source);
}

const HEADER =
  "// GENERATED by `npm run notes:diagrams` from diagramRegistry.tsx. Do not edit.\n" +
  "// Why two files: src/lib/notes/diagramSplit.ts. Drift check: tests/notes-diagram-split.test.ts.\n";

export function buildServerDiagramsModule(entries: DiagramEntry[], isClientFile: (file: string) => boolean): string {
  const server = entries.filter((e) => !isClientFile(e.file));
  const imports = [...new Map(server.map((e) => [e.component, e.file])).entries()]
    .map(([component, file]) => `import ${component} from "./visualizations/${file}";`);
  const cases = server.map((e) => `    case ${JSON.stringify(e.slug)}:\n      return <${e.component} />;`);
  return (
    HEADER +
    "// The picture-only diagrams: drawn on the server, no browser code.\n" +
    'import type { ReactElement } from "react";\n' +
    'import type { VisualizationSlug } from "@/app/notes/_types";\n' +
    imports.join("\n") +
    "\n\n" +
    "/** A picture-only diagram, or null when the slug's diagram runs in the browser. */\n" +
    "export function renderServerDiagram(slug: VisualizationSlug): ReactElement | null {\n" +
    "  switch (slug) {\n" +
    cases.join("\n") +
    "\n    default:\n      return null;\n  }\n}\n"
  );
}

export function buildClientDiagramModule(entries: DiagramEntry[], isClientFile: (file: string) => boolean): string {
  const client = entries.filter((e) => isClientFile(e.file));
  const loaders = client.map((e) => `  ${JSON.stringify(e.slug)}: dynamic(() => import("./visualizations/${e.file}")),`);
  return (
    '"use client";\n' +
    HEADER +
    "// The browser-run diagrams: each its own script, downloaded only by a page that shows it.\n" +
    'import dynamic from "next/dynamic";\n' +
    'import type { ComponentType } from "react";\n' +
    'import type { VisualizationSlug } from "@/app/notes/_types";\n\n' +
    "const DIAGRAMS: Partial<Record<VisualizationSlug, ComponentType>> = {\n" +
    loaders.join("\n") +
    "\n};\n\n" +
    "export default function ClientDiagram({ slug }: { slug: VisualizationSlug }) {\n" +
    "  const Diagram = DIAGRAMS[slug];\n" +
    "  return Diagram ? <Diagram /> : null;\n" +
    "}\n"
  );
}

/**
 * Generated database types and the typed clients (TECH_DEBT_SPEC.md 3.3).
 *
 * WHY: no Supabase client was typed (0 uses of `<Database>` on 2026-11-05), so every read came
 * back as `any` and 50 of the 65 `as unknown as` casts in src/ were forcing row shapes by hand.
 * `npm run db:types` writes src/types/db.ts from the live schema; the typed clients use it.
 * New code reads through a typed client; existing modules move over when they are edited.
 *
 * The expectTypeOf checks run at TYPECHECK time (`npm run typecheck` covers tests); the queries
 * below are never executed.
 */
import { describe, it, expect, expectTypeOf } from "vitest";
import fs from "node:fs";
import path from "node:path";
import type { Database } from "@/types/db";
import { createTypedAnonClient, createTypedServerClient } from "@/lib/supabase/server";
import { createTypedAdminClient } from "@/lib/supabase/admin";
import { createTypedBrowserClient } from "@/lib/supabase/client";
import { typesDrift } from "../scripts/db/genTypesCore";

type Format = Database["public"]["Enums"]["question_format"];

async function anonShape() {
  const { data } = await createTypedAnonClient().from("questions").select("id, question_format").limit(1);
  return data;
}
async function adminShape() {
  const { data } = await createTypedAdminClient().from("mock_attempts").select("id, user_id").limit(1);
  return data;
}

async function serverShape() {
  const { data } = await createTypedServerClient().from("question_bookmarks").select("question_id").limit(1);
  return data;
}

async function browserShape() {
  const { data } = await createTypedBrowserClient().from("notes_progress").select("user_id").limit(1);
  return data;
}

describe("typed clients", () => {
  it("type a query's rows from the schema", () => {
    expectTypeOf<Awaited<ReturnType<typeof anonShape>>>().toEqualTypeOf<{ id: string; question_format: Format }[] | null>();
    expectTypeOf<Awaited<ReturnType<typeof adminShape>>>().toEqualTypeOf<{ id: string; user_id: string }[] | null>();
    expectTypeOf<Awaited<ReturnType<typeof serverShape>>>().toEqualTypeOf<{ question_id: string }[] | null>();
    expectTypeOf<Awaited<ReturnType<typeof browserShape>>>().toEqualTypeOf<{ user_id: string }[] | null>();
  });
});

describe("src/types/db.ts", () => {
  const file = path.join(process.cwd(), "src", "types", "db.ts");
  it("is committed, generated from the schema", () => {
    const src = fs.readFileSync(file, "utf8");
    expect(src).toMatch(/^\/\/ GENERATED by `npm run db:types`/);
    expect(src).toMatch(/export type Database = \{/);
  });
});

describe("typesDrift", () => {
  it("ignores line endings and a trailing newline", () => {
    expect(typesDrift("a\r\nb\r\n", "a\nb")).toBe(false);
  });
  it("reports a real difference", () => {
    expect(typesDrift("a\nb\n", "a\nc\n")).toBe(true);
  });
});

/**
 * Build the India outline for Pin It (/play/pin-it) from Survey of India's
 * official outline: https://surveyofindia.gov.in/documents/Outline_of_India.zip
 * (the "Outline maps of India" page). Download and unzip it, then:
 *
 *   npx tsx scripts/play/build-india-map.ts <path to Outline_of_India.shp>
 *
 * Writes src/lib/play/data/indiaOutline.generated.ts: one SVG path in
 * kilometres in Survey of India's own projection (Lambert Conformal Conic,
 * lib/play/pin LCC), simplified to 2 km, which is far below one pixel on a
 * phone. Islands under 0.5 km² go; at 4 km² Lakshadweep would lose 28 of its
 * 30 islands (checked 2026-11-17), so never raise that floor without looking.
 * Owner decision 2026-11-17: use SoI's official outline (the games are free).
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const TOLERANCE_M = 2000;
const MIN_ISLAND_M2 = 0.5e6;
const SMALL_ISLAND_M2 = 50e6;
const SMALL_TOLERANCE_M = 150;

type Pt = [number, number];

function readPolygons(file: string): Pt[][] {
  const b = readFileSync(file);
  const type = b.readInt32LE(32);
  if (type !== 5) throw new Error(`Expected a polygon shapefile (type 5), got ${type}.`);
  const rings: Pt[][] = [];
  let off = 100;
  while (off < b.length) {
    const len = b.readInt32BE(off + 4) * 2;
    const c = off + 8;
    off = c + len;
    if (b.readInt32LE(c) === 0) continue;
    const nParts = b.readInt32LE(c + 36);
    const nPts = b.readInt32LE(c + 40);
    const parts: number[] = [];
    for (let i = 0; i < nParts; i++) parts.push(b.readInt32LE(c + 44 + 4 * i));
    parts.push(nPts);
    const base = c + 44 + 4 * nParts;
    for (let i = 0; i < nParts; i++) {
      const ring: Pt[] = [];
      for (let k = parts[i]; k < parts[i + 1]; k++) ring.push([b.readDoubleLE(base + 16 * k), b.readDoubleLE(base + 16 * k + 8)]);
      rings.push(ring);
    }
  }
  return rings;
}

function area(r: Pt[]): number {
  let s = 0;
  for (let i = 0; i < r.length; i++) {
    const [x1, y1] = r[i === 0 ? r.length - 1 : i - 1];
    const [x2, y2] = r[i];
    s += x1 * y2 - x2 * y1;
  }
  return Math.abs(s) / 2;
}

/** Douglas-Peucker on an open polyline. */
function dp(pts: Pt[], tol: number): Pt[] {
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack: [number, number][] = [[0, pts.length - 1]];
  while (stack.length) {
    const [i, j] = stack.pop()!;
    const [x1, y1] = pts[i];
    const [x2, y2] = pts[j];
    const dx = x2 - x1;
    const dy = y2 - y1;
    const L = Math.hypot(dx, dy) || 1e-9;
    let best = 0;
    let bi = -1;
    for (let k = i + 1; k < j; k++) {
      const d = Math.abs(dy * (pts[k][0] - x1) - dx * (pts[k][1] - y1)) / L;
      if (d > best) {
        best = d;
        bi = k;
      }
    }
    if (best > tol) {
      keep[bi] = 1;
      stack.push([i, bi], [bi, j]);
    }
  }
  return pts.filter((_, k) => keep[k]);
}

/**
 * A closed ring returns 2 points from plain DP (start = end), so simplify each
 * half. Small islands get a finer tolerance: at 2 km a Lakshadweep island
 * collapses below 4 points and vanishes.
 */
function simplifyRing(r: Pt[]): Pt[] {
  const tol = area(r) < SMALL_ISLAND_M2 ? SMALL_TOLERANCE_M : TOLERANCE_M;
  const h = Math.floor(r.length / 2);
  return [...dp(r.slice(0, h + 1), tol).slice(0, -1), ...dp(r.slice(h), tol)];
}

function main() {
  const file = process.argv[2];
  if (!file) throw new Error("Usage: npx tsx scripts/play/build-india-map.ts <Outline_of_India.shp>");
  const rings = readPolygons(file);
  const kept = rings.filter((r) => area(r) >= MIN_ISLAND_M2).map(simplifyRing).filter((r) => r.length >= 4);
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const r of kept)
    for (const [x, y] of r) {
      minX = Math.min(minX, x); minY = Math.min(minY, y); maxX = Math.max(maxX, x); maxY = Math.max(maxY, y);
    }
  const km = (v: number) => (v / 1000).toFixed(1);
  // SVG y grows downward: flip about maxY.
  const d = kept
    .map((r) => "M" + r.map(([x, y]) => `${km(x - minX)} ${km(maxY - y)}`).join("L") + "Z")
    .join("");
  const out = `// GENERATED by scripts/play/build-india-map.ts from Survey of India's official
// Outline_of_India shapefile. Do not edit by hand; re-run the script.
// ${kept.length} rings (of ${rings.length}), ${kept.reduce((n, r) => n + r.length, 0)} points, simplified to ${TOLERANCE_M / 1000} km.

/** The map's frame in Survey of India's LCC metres (lib/play/pin). */
export const INDIA_FRAME = { minX: ${minX.toFixed(0)}, maxY: ${maxY.toFixed(0)}, widthKm: ${km(maxX - minX)}, heightKm: ${km(maxY - minY)} } as const;

/** India's outline as one SVG path, in kilometres from the frame's top-left. */
export const INDIA_PATH =
  "${d}";
`;
  const target = path.join(process.cwd(), "src/lib/play/data/indiaOutline.generated.ts");
  writeFileSync(target, out);
  console.log(`Wrote ${target}: ${kept.length} rings, ${(out.length / 1024).toFixed(0)} KB.`);
}

main();

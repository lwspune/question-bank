/**
 * Write src/lib/notes/chapterLoaders.generated.ts: the notes chapter INDEX (every registry
 * field except the content) and one lazy loader per chapter, so a /notes route loads one
 * chapter's `_data` instead of the whole corpus (TECH_DEBT_SPEC.md 2.2 part 2).
 *
 *   npm run notes:chapter-loaders              # regenerate
 *   npm run notes:chapter-loaders -- --check   # exit 1 if the committed file is stale
 *
 * RUN AFTER SHIPPING OR RENAMING A NOTES CHAPTER and commit the result (beside
 * notes:nav-index and chat:notes-data); tests/notes-chapter-loaders.test.ts fails until you do.
 * Export names are found by identity against the registry, as scripts/chat/gen-notes-data.ts does.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { NOTES_CHAPTERS } from "@/lib/notes/chapters";
import { buildNotesChapterIndex } from "@/lib/notes/chapterIndexBuild";

const OUT = path.resolve(__dirname, "../../src/lib/notes/chapterLoaders.generated.ts");
const SRC = path.resolve(__dirname, "../../src");

/** A chapter's data module: under src/app/notes, or for IMAT under src/lib/sites/imat/notes. */
function dataModule(subjectRoute: string, chapterSlug: string): string {
  const candidates = [`app/notes/${subjectRoute}/${chapterSlug}/_data`];
  if (subjectRoute.startsWith("imat-")) candidates.push(`lib/sites/imat/notes/${subjectRoute.slice("imat-".length)}/${chapterSlug}`);
  const found = candidates.find((c) => existsSync(path.join(SRC, c, "index.ts")));
  if (!found) throw new Error(`${subjectRoute}/${chapterSlug}: no data module at ${candidates.map((c) => `src/${c}/index.ts`).join(" or ")}`);
  return `@/${found}`;
}

async function main() {
  const index = buildNotesChapterIndex(NOTES_CHAPTERS);
  const loaders: string[] = [];
  for (const c of NOTES_CHAPTERS) {
    const spec = dataModule(c.subjectRoute, c.chapterSlug);
    const mod = (await import(spec)) as Record<string, unknown>;
    const chapterName = Object.keys(mod).find((k) => mod[k] === c.chapter);
    const notesName = Object.keys(mod).find((k) => mod[k] === c.notes);
    if (!chapterName || !notesName) throw new Error(`${spec} does not export the registry's chapter and notes objects`);
    const key = `${c.subjectRoute}/${c.chapterSlug}`;
    loaders.push(`  ${JSON.stringify(key)}: () => import("${spec}").then((m) => ({ chapter: m.${chapterName}, notes: m.${notesName} })),`);
  }

  const body =
    "// GENERATED by `npm run notes:chapter-loaders` from src/lib/notes/chapters.ts — do not edit.\n" +
    "// The notes chapter index and one lazy loader per chapter, so a /notes route loads one\n" +
    "// chapter's content, not the corpus. Why: src/lib/notes/chapterIndex.ts.\n" +
    "// Drift check: tests/notes-chapter-loaders.test.ts.\n" +
    'import type { ChapterNote, SubtopicNote } from "@/app/notes/_types";\n' +
    'import type { NotesChapterMeta } from "./chapterIndex";\n\n' +
    `export const NOTES_CHAPTER_INDEX: readonly NotesChapterMeta[] = ${JSON.stringify(index, null, 2)};\n\n` +
    "export const NOTES_CHAPTER_LOADERS: Record<string, () => Promise<{ chapter: ChapterNote; notes: Record<string, SubtopicNote> }>> = {\n" +
    loaders.join("\n") +
    "\n};\n";

  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== body) {
      console.error(`${path.basename(OUT)} is stale — run \`npm run notes:chapter-loaders\` and commit it.`);
      process.exit(1);
    }
    console.log(`${path.basename(OUT)} is current (${index.length} chapters).`);
  } else {
    writeFileSync(OUT, body);
    console.log(`wrote ${path.relative(process.cwd(), OUT)} (${index.length} chapters)`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

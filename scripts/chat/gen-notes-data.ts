/**
 * Write src/lib/chat/notesData.generated.ts: one lazy loader per notes chapter,
 * so V can read the practice question a student tapped Ask V on without its
 * answer route importing the whole notes registry (the 2026-10-02 AppHeader
 * lesson: that registry pulls in every _data module).
 *
 *   npm run chat:notes-data              # regenerate
 *   npm run chat:notes-data -- --check   # exit 1 if the committed file is stale
 *
 * RUN AFTER SHIPPING OR RENAMING A NOTES CHAPTER and commit the result;
 * tests/chat-notes-item.test.ts fails until you do.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { NOTES_CHAPTERS } from "@/lib/notes/chapters";
import { notesDataKeys } from "@/lib/chat/notesItem";

const OUT = path.resolve(__dirname, "../../src/lib/chat/notesData.generated.ts");
const SRC = path.resolve(__dirname, "../../src");

/** A chapter's data module: under src/app/notes, or for IMAT (authored in its
 *  own tree) src/lib/sites/imat/notes/<subject>/<chapter>. */
function dataModule(key: string): string {
  const [route, chapter] = key.split("/");
  const candidates = [`app/notes/${key}/_data`];
  if (route.startsWith("imat-")) candidates.push(`lib/sites/imat/notes/${route.slice("imat-".length)}/${chapter}`);
  const found = candidates.find((c) => existsSync(path.join(SRC, c, "index.ts")));
  if (!found) throw new Error(`${key}: no data module at ${candidates.map((c) => `src/${c}/index.ts`).join(" or ")}`);
  return `@/${found}`;
}

async function main() {
  const keys = notesDataKeys(NOTES_CHAPTERS);
  const loaders: string[] = [];
  for (const key of keys) {
    const reg = NOTES_CHAPTERS.find((c) => `${c.subjectRoute}/${c.chapterSlug}` === key)!;
    const spec = dataModule(key);
    const mod = (await import(spec)) as Record<string, unknown>;
    const name = Object.keys(mod).find((k) => mod[k] === reg.notes);
    if (!name) throw new Error(`${key}: ${spec} exports no object that is the registry's notes map`);
    loaders.push(`  ${JSON.stringify(key)}: () => import("${spec}").then((m) => m.${name}),`);
  }

  const body =
    "// GENERATED by `npm run chat:notes-data` from src/lib/notes/chapters.ts — do not edit.\n" +
    "// One lazy loader per notes chapter, for V's Ask V on notes questions (lib/chat/notesItem.ts).\n" +
    "// Drift check: tests/chat-notes-item.test.ts.\n" +
    'import type { SubtopicNote } from "@/app/notes/_types";\n\n' +
    `export const NOTES_DATA_KEYS: readonly string[] = ${JSON.stringify(keys, null, 2)};\n\n` +
    "export const NOTES_DATA_LOADERS: Record<string, () => Promise<Record<string, SubtopicNote>>> = {\n" +
    loaders.join("\n") +
    "\n};\n";

  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== body) {
      console.error("notesData.generated.ts is stale — run `npm run chat:notes-data` and commit it.");
      process.exit(1);
    }
    console.log(`notesData.generated.ts is current (${keys.length} chapters).`);
  } else {
    writeFileSync(OUT, body);
    console.log(`wrote ${path.relative(process.cwd(), OUT)} (${keys.length} chapters)`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

/**
 * Regenerate src/lib/board/revision/loaders.generated.ts from the sheet files
 * (2026-11-03): `npm run revision:registry`. One lazy loader per file under
 * src/lib/board/revision/sheets/, keyed by its path. RUN AFTER ADDING OR
 * RENAMING A SHEET; tests/board-revision-registry.test.ts fails until you do.
 */
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const ROOT = join(__dirname, "..", "..", "src", "lib", "board", "revision");
const SHEETS = join(ROOT, "sheets");

function files(dir: string): string[] {
  return readdirSync(dir)
    .flatMap((name) => {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) return files(p);
      return name.endsWith(".ts") ? [relative(SHEETS, p).split(sep).join("/").replace(/\.ts$/, "")] : [];
    })
    .sort();
}

const keys = files(SHEETS);
const body = keys.map((k) => `  "${k}": () => import("./sheets/${k}"),`).join("\n");
writeFileSync(
  join(ROOT, "loaders.generated.ts"),
  `// GENERATED by \`npm run revision:registry\` from src/lib/board/revision/sheets/ — do not edit.\n` +
    `// One lazy loader per sheet file, keyed "<examSlug>/<subjectRoute>/<chapterSlug>".\n` +
    `import type { RevisionSheet } from "./types";\n\n` +
    `export const SHEET_LOADERS: Record<string, () => Promise<{ default: RevisionSheet }>> = {\n${body}\n};\n`
);
console.log(`${keys.length} sheet(s) registered`);
